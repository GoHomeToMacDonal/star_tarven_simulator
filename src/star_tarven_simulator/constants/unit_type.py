# 固定单位分类。精英/皇家卫队只是基础单位的品质后缀，分类查询必须继承
# 基础单位属性；调用方仍可直接使用 ``unit in *_UNITS`` 的 membership API。
_VARIANT_SUFFIXES = ("(精英)", "(皇家卫队)")


def normalize_unit_name(unit: str) -> str:
    """移除已知品质后缀，返回分类使用的基础单位名。"""
    for suffix in _VARIANT_SUFFIXES:
        if unit.endswith(suffix):
            return unit[: -len(suffix)]
    return unit


def _expand_variants(units) -> frozenset[str]:
    bases = {normalize_unit_name(unit) for unit in units}
    return frozenset(
        bases
        | {f"{unit}{suffix}" for unit in bases for suffix in _VARIANT_SUFFIXES}
    )


